// Calendar Events
fun List<Any>?.toCourseEvents(): List<CourseEvent> {
  return this?.mapNotNull { item ->
    val map = item.asMap() ?: return@mapNotNull null

    val startStr = map.getString("start") ?: map.getString("data_inizio")
    val endStr = map.getString("end") ?: map.getString("data_fine")

    val start = try {
      LocalDateTime.parse(startStr, DateTimeFormatter.ISO_DATE_TIME)
    } catch (e: Exception) {
      LocalDateTime.now()
    }
    val end = try {
      LocalDateTime.parse(endStr, DateTimeFormatter.ISO_DATE_TIME)
    } catch (e: Exception) {
      start.plusHours(1)
    }

    CourseEvent(
      id = 0, // Generated by Room
      courseName = map.getString("title") ?: map.getString("nome") ?: "Event",
      courseCode = map.getString("code") ?: map.getString("codice"),
      professor = map.getString("professor") ?: map.getString("docente"),
      room = map.getString("room") ?: map.getString("aula"),
      building = map.getString("building") ?: map.getString("edificio"),
      startTime = start,
      endTime = end,
      eventType = EventType.LECTURE, // Defaulting
      notes = map.getString("description"),
      color = map.getString("color")
    )
  } ?: emptyList()
}

