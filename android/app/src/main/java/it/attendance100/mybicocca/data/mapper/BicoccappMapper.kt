import java.time.*
import java.time.format.*

// Helper extensions for manual mapping from LinkedTreeMap (Gson's default for Any)
@Suppress("UNCHECKED_CAST")
fun Any?.asMap(): Map<String, Any?>? = this as? Map<String, Any?>
fun Any?.asList(): List<Any?>? = this as? List<Any?>
fun Map<String, Any?>.getString(key: String): String? = this[key]?.toString()
fun Map<String, Any?>.getDouble(key: String): Double? = (this[key] as? Number)?.toDouble()
fun Map<String, Any?>.getInt(key: String): Int? = (this[key] as? Number)?.toInt()
fun Map<String, Any?>.getBoolean(key: String): Boolean? = this[key] as? Boolean

// --- Payments ---
fun List<Any>?.toPayments(): List<Payment> {
  return this?.mapNotNull { item ->
    val map = item.asMap() ?: return@mapNotNull null
    Payment(
      id = map.getString("invoiceId") ?: map.getString("fatt_id") ?: "",
      title = map.getString("description") ?: map.getString("descrizione") ?: "Payment",
      amount = map.getDouble("amount") ?: map.getDouble("importo") ?: 0.0,
      deadline = map.getString("deadline")?.parseDate() ?: LocalDate.MIN,
      status = parsePaymentStatus(map.getString("status")),
      invoiceUrl = map.getString("url")
    )
  } ?: emptyList()
}

private fun String?.parseDate(): LocalDate? {
  if (this == null) return null
  return try {
    // Try ISO
    LocalDate.parse(this, DateTimeFormatter.ISO_DATE)
  } catch (e: Exception) {
    // Try Italian format?
    try {
      LocalDate.parse(this, DateTimeFormatter.ofPattern("dd/MM/yyyy"))
    } catch (e2: Exception) {
      LocalDate.now() // Fallback
    }
  }
}

private fun parsePaymentStatus(status: String?): PaymentStatus {
  return when (status?.lowercase()) {
    "paid", "pagato" -> PaymentStatus.PAID
    "overdue", "scaduto" -> PaymentStatus.OVERDUE
    "cancelled", "annullato" -> PaymentStatus.CANCELLED
    else -> PaymentStatus.UNPAID
  }
}

