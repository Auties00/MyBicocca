package it.attendance100.mybicocca.codegen.core

import it.attendance100.mybicocca.codegen.model.TypeRef
import it.attendance100.mybicocca.codegen.testing.SampleSpecs
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.jsonObject
import org.junit.jupiter.api.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

class ResourcesTest {
    private val owner = TypeRef.Named("DemoOwner")

    @Test
    fun `accepts data that fits its type`() {
        assertEquals(emptyList(), ResourceData.validate(SampleSpecs.demo, owner, Json.parseToJsonElement("""{"ownerId": 7}"""), "owners"))
    }

    @Test
    fun `reports missing keys, unknown keys and values of another type`() {
        val missing = ResourceData.validate(SampleSpecs.demo, owner, JsonObject(emptyMap()), "owners")
        assertEquals(listOf("owners.ownerId: missing"), missing)
        val unknown = ResourceData.validate(SampleSpecs.demo, owner, Json.parseToJsonElement("""{"ownerId": 7, "name": "Ada"}"""), "owners")
        assertEquals(listOf("owners.name: not in DemoOwner"), unknown)
        val wrong = ResourceData.validate(SampleSpecs.demo, owner, Json.parseToJsonElement("""{"ownerId": "7"}"""), "owners")
        assertTrue(wrong.single().startsWith("owners.ownerId: expected int64"))
    }

    @Test
    fun `writes minified JSON whose first key carries the generated marker`() {
        val json = resourceJson("demo", SampleSpecs.demoResources.values.single())
        assertEquals("""{"_generated":"Generated by MyBicocca codegen for demo. Do not edit.","ownerId":7}""", json)
        assertEquals(SampleSpecs.demoResources.values.single().getValue("ownerId"), Json.parseToJsonElement(json).jsonObject.getValue("ownerId"))
    }
}
